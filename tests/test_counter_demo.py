# Determinism — running the same demo twice gives identical content hashes.
# --------------------------------------------------------------------------- #
def test_counter_demo_two_runs_produce_identical_manifests(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    run_a = tmp_path / "a"
    run_b = tmp_path / "b"
    manifest_a, _ = _drive_demo(run_a, config_path=routing_config)
    manifest_b, _ = _drive_demo(run_b, config_path=routing_config)
    by_id_a = {(e.artifact_id, e.version): e.content_hash for e in manifest_a.entries}
    by_id_b = {(e.artifact_id, e.version): e.content_hash for e in manifest_b.entries}
    assert by_id_a == by_id_b


def test_counter_demo_changing_design_id_yields_distinct_artifacts(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    """Different ``design_id`` -> different artifact_ids AND content hashes.

    ``design_id`` is part of the content body (it's not in
    :data:`Artifact._NON_CONTENT_FIELDS`), so two runs of the same spec
    under different ids produce two independent artifact DAGs. This is
    the property the manifest comparator relies on.
    """
    manifest_g, _ = _drive_demo(
        tmp_path / "golden", config_path=routing_config, design_id=GOLDEN_DESIGN_ID,
    )
    manifest_x, _ = _drive_demo(
        tmp_path / "other", config_path=routing_config, design_id="counter-other",
    )
    hashes_g = {e.kind: e.content_hash for e in manifest_g.entries}
    hashes_x = {e.kind: e.content_hash for e in manifest_x.entries}
    assert hashes_g != hashes_x
    ids_g = {e.artifact_id for e in manifest_g.entries}
    ids_x = {e.artifact_id for e in manifest_x.entries}
    assert not (ids_g & ids_x)


