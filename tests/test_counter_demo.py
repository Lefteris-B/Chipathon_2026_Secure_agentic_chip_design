"""F8.3 — counter demo run + golden manifest reproducibility.

Drives ``specs/counter.md`` through the F8.1 CLI (``cmd_run`` +
``cmd_resume``) with deterministic args and asserts:

* The newly-produced manifest matches the committed
  ``tests/fixtures/counter_golden_manifest.json`` bit-for-bit on
  every ``content_hash`` — the F8.3 reproducibility AC.
* ``compare_to_manifest`` of the committed manifest is
  ``reproducible=True`` against a fresh store.
* The hash-chained audit log verifies clean end-to-end.
* The trace tree built from the run + resume tracer covers all
  seven stages (SPEC → PLAN → RTL → SYNTH → PHYSICAL → SIGNOFF →
  GDSII).

F10.1 routes the spec + plan through the real :class:`SpecIntakeAgent` +
:class:`PlannerAgent` over a stub :class:`CompletionBackend`. The
committed golden manifest is regenerated by re-running this demo
whenever the stub responses change.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from chip_agent.cli import RunArgs, cmd_resume, cmd_run
from chip_agent.design_state import ArtifactKind, Stage
from chip_agent.obs.audit_log import SqliteAuditLog
from chip_agent.obs.replay import RunManifest, compare_to_manifest
from chip_agent.obs.tracing import InMemoryTracer, SpanKind, build_trace_tree
from chip_agent.store.sqlite_store import SqliteArtifactStore
from tests._routing_stub import (
    StubBackend,
    make_routing_config,
    make_test_router,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
COUNTER_SPEC = REPO_ROOT / "specs" / "counter.md"
GOLDEN_MANIFEST_PATH = REPO_ROOT / "tests" / "fixtures" / "counter_golden_manifest.json"
GOLDEN_DESIGN_ID = "counter-demo-golden"
HMAC_KEY = b"f8-3-counter-demo-hmac-key"


@pytest.fixture
def routing_config(tmp_path: Path) -> Path:
    return make_routing_config(tmp_path)


@pytest.fixture
def patch_router(
    monkeypatch: pytest.MonkeyPatch,
    routing_config: Path,
) -> StubBackend:
    backend = StubBackend()
    router, _ = make_test_router(config_path=routing_config, backend=backend)
    monkeypatch.setattr("chip_agent.cli._resolve_router", lambda _args, *, settings: router)
    return backend


def _args(
    *,
    cmd: str,
    run_dir: Path,
    design_id: str,
    config_path: Path,
    spec_path: Path | None = None,
    name: str | None = None,
    tracer: InMemoryTracer | None = None,
) -> RunArgs:
    return RunArgs(
        cmd=cmd, spec_path=spec_path, name=name, run_dir=run_dir,
        design_id=design_id, hmac_key=HMAC_KEY, tracer=tracer,
        config_path=config_path,
    )


def _drive_demo(
    run_dir: Path,
    *,
    config_path: Path,
    design_id: str = GOLDEN_DESIGN_ID,
    tracer: InMemoryTracer | None = None,
) -> tuple[RunManifest, Path]:
    """Run the counter spec end-to-end through the CLI; return its manifest."""
    cmd_run(_args(
        cmd="run", run_dir=run_dir, design_id=design_id,
        spec_path=COUNTER_SPEC, name="counter", tracer=tracer,
        config_path=config_path,
    ))
    out = cmd_resume(_args(
        cmd="resume", run_dir=run_dir, design_id=design_id, tracer=tracer,
        config_path=config_path,
    ))
    return out.manifest, out.manifest_path


# --------------------------------------------------------------------------- #
# Fixture sanity — the committed golden exists and is well-formed.
# --------------------------------------------------------------------------- #
def test_committed_golden_manifest_exists_and_is_valid_json() -> None:
    assert GOLDEN_MANIFEST_PATH.exists(), (
        f"committed golden manifest missing at {GOLDEN_MANIFEST_PATH}"
    )
    payload = json.loads(GOLDEN_MANIFEST_PATH.read_text())
    assert payload["design_id"] == GOLDEN_DESIGN_ID
    assert payload["root_ref"]["kind"] == "gdsii"


# --------------------------------------------------------------------------- #
# F8.3 AC strand 1 — committed manifest reproduces against a fresh run.
# --------------------------------------------------------------------------- #
def test_counter_demo_run_reproduces_golden_manifest(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    fresh, _ = _drive_demo(tmp_path, config_path=routing_config)
    golden = RunManifest.model_validate_json(GOLDEN_MANIFEST_PATH.read_text())

    assert fresh.design_id == golden.design_id
    assert fresh.root_ref.content_hash == golden.root_ref.content_hash, (
        "GDS content_hash drifted from golden — stub templates changed?"
    )

    fresh_by_id = {f"{e.artifact_id}@v{e.version}": e for e in fresh.entries}
    golden_by_id = {f"{e.artifact_id}@v{e.version}": e for e in golden.entries}
    assert set(fresh_by_id) == set(golden_by_id), (
        f"manifest entries diverged from golden: "
        f"only in fresh={set(fresh_by_id) - set(golden_by_id)}, "
        f"only in golden={set(golden_by_id) - set(fresh_by_id)}"
    )
    for key, golden_entry in golden_by_id.items():
        fresh_entry = fresh_by_id[key]
        assert fresh_entry.content_hash == golden_entry.content_hash, (
            f"{key}: content_hash diverged from golden "
            f"(fresh={fresh_entry.content_hash}, golden={golden_entry.content_hash})"
        )
        assert fresh_entry.kind is golden_entry.kind


def test_counter_demo_compare_to_manifest_is_reproducible(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    """F7.3 ``compare_to_manifest`` verifies clean against the fresh store."""
    fresh, _ = _drive_demo(tmp_path, config_path=routing_config)
    with SqliteArtifactStore(
        db_path=tmp_path / "store.sqlite", content_dir=tmp_path / "content",
    ) as store:
        diff = compare_to_manifest(store, fresh)
    assert diff.reproducible, (
        f"fresh manifest does not verify against its own store: "
        f"missing={diff.missing!r}, mismatched={diff.mismatched!r}"
    )
    assert len(diff.matched) == 6  # spec, plan, rtl, netlist, layout, gds
    assert not diff.skipped         # no diagnosis artifacts in F8.3


def test_committed_golden_verifies_against_fresh_run_store(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    """The committed manifest must verify clean against a fresh run's store."""
    _drive_demo(tmp_path, config_path=routing_config)
