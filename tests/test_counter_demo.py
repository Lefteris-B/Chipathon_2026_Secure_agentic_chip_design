# F9.5 — TestbenchGenAgent populates the store with a cocotb testbench.
# --------------------------------------------------------------------------- #
def test_counter_demo_store_contains_cocotb_testbench(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    """The TB lands in the content store as the F19.8 differential harness.

    The TB doesn't currently appear in the run manifest — its ref lives
    in the simulation result's provenance, which is on the RTL stage's
    ``ss.results`` (not on the GDS lineage walk ``manifest_from_run``
    follows). The TB is still required to reproduce the run; this test
    pins that it's persisted with the right shape.

    Since F19.7 promotes per-module oracle + assertion heads before
    RTL, the F19.8 dispatch path triggers and the persisted TB is the
    deterministic differential harness — STIM/EXPECTED literals,
    ``getattr(dut, port)`` access, ``DIFF|...`` canonical assertion
    message. The legacy templated F9.5 TB now only fires when M19
    artifacts are missing (back-compat unit tests).
    """
    _drive_demo(tmp_path, config_path=routing_config)
    with SqliteArtifactStore(
        db_path=tmp_path / "store.sqlite", content_dir=tmp_path / "content",
    ) as store:
        tb = store.get_by_id(f"{GOLDEN_DESIGN_ID}.counter.tb")
        body = store.get_blob(tb.source).decode("utf-8")
    assert tb.kind is ArtifactKind.TESTBENCH
    assert tb.framework == "cocotb"
    assert tb.target_module == "counter"
    # F19.8 differential shape: embedded STIM/EXPECTED + canonical DIFF
    # token + the counter's clock and data ports referenced by name.
    assert "import cocotb" in body
    assert "STIM = " in body
    assert "EXPECTED = " in body
    assert "DIFF|cycle=" in body
    assert "'clk'" in body
    assert "'rst_n'" in body
    assert "'en'" in body
    assert "'q'" in body
    assert "assert " in body


def test_counter_demo_simulation_result_links_to_testbench(
    tmp_path: Path, routing_config: Path, patch_router: StubBackend,
) -> None:
    """The RTL stage's stored sim result has the TB on its lineage.

    This is the channel by which a replay reproduces the verification
    decision the RTL stage made — even though the manifest doesn't
    include the TB directly.
    """
    _drive_demo(tmp_path, config_path=routing_config)
    with SqliteArtifactStore(
        db_path=tmp_path / "store.sqlite", content_dir=tmp_path / "content",
    ) as store:
        sim = store.get_by_id(f"{GOLDEN_DESIGN_ID}.counter.sim")
        tb = store.get_by_id(f"{GOLDEN_DESIGN_ID}.counter.tb")
    tb_refs = [r for r in sim.provenance.inputs if r.kind is ArtifactKind.TESTBENCH]
    assert len(tb_refs) == 1
    assert tb_refs[0] == tb.ref()


